"""
ObfuscationArena: Explain obfuscated code at increasing levels.

Environment concept:
  The model is given obfuscated Python code and must explain what it does.
  The code is generated by taking simple, readable functions and obfuscating
  them (renaming variables to single letters, removing whitespace, combining
  expressions). The model must identify the original intent.

  Why: explaining obfuscated code requires deep semantic understanding —
  the model cannot pattern-match on variable names or structure. It must
  reason about what the code *does*, not what it *looks like*.

Verification:
  - Check if the explanation mentions key concepts from the original code
    (function name, operations, return value).
  - Partial credit for each keyword found.

Reward design:
  fraction of key_concepts mentioned in the explanation.
"""

